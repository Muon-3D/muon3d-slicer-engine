#!/usr/bin/env node
// Records the neighbour slice goldens (`neighbours` in test/goldens/slices.json): the plates of NEIGHBOUR_PLATES
// (test/conformance/plates.ts), several objects with supports, none within reach of another's organic tree supports
// (or with supports of another kind), sliced on both variants by the engine in the given folder, through the host's
// own request checks (host/src/ops.ts) and the bridge (host/src/bridge.ts). Recorded with the v0.4.0 release, from
// before the plate's other objects became support blockers (2.3): the conformance suite then requires every later
// engine to give the same G-code, the "; generated by" line aside.
//
//   node tools/goldens/record-slices-neighbours.mjs <engine folder>   # e.g. the v0.4.0 runtime, extracted
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadEngine, runSlice } from '../../host/src/bridge.ts';
import { sliceJob } from '../../host/src/ops.ts';
import { NEIGHBOUR_PLATES, comparable } from '../../test/conformance/plates.ts';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
if (!process.argv[2]) throw new Error('usage: record-slices-neighbours.mjs <engine folder>');
const engineDir = path.resolve(process.argv[2]);
const manifest = JSON.parse(fs.readFileSync(path.join(engineDir, 'manifest.json'), 'utf8'));

const plates = {};
for (const variant of ['st', 'mt']) {
  const { engine } = await loadEngine(pathToFileURL(engineDir + path.sep).href, variant);
  for (const plate of NEIGHBOUR_PLATES) {
    const output = runSlice(engine, { ...sliceJob(plate.params()), toolpaths: false });
    (plates[plate.id] ??= {})[variant] = {
      sha256: createHash('sha256').update(comparable(output.gcode)).digest('hex'),
      bytes: output.gcode.length,
      layers: output.stats.layers,
      printTimeText: output.stats.printTimeText,
      filamentMm: output.stats.filamentMm,
    };
  }
  console.log(`${variant}: ${NEIGHBOUR_PLATES.length} plates`);
}
for (const [id, { st, mt }] of Object.entries(plates)) {
  if (st.sha256 !== mt.sha256) throw new Error(`${id}: st and mt give different G-code (${st.sha256} and ${mt.sha256})`);
}

const out = path.join(repo, 'test/goldens/slices.json');
const goldens = JSON.parse(fs.readFileSync(out, 'utf8'));
goldens.neighbours = {
  reference: {
    version: manifest.version,
    orcaCommit: manifest.orcaCommit,
    recordedWith: `the engine ${manifest.version} (st and mt alike), before the plate's other objects became support blockers`,
  },
  plates,
};
fs.writeFileSync(out, JSON.stringify(goldens, null, 1) + '\n');
console.log(`OK: ${out}`);
