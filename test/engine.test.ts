  test("object settings: layer height 0.1 and 5 walls on one cube, as Orca's CLI slices it from a 3MF", (t) => {
    const sliced = slice(engine, presets, objectSettingsPlate());
    const { output } = sliced;
    report(t, 'object settings', sliced);
    t.diagnostic(`G-code: ${saveGcode('object-settings.gcode', output.gcode)}`);
    assertStatsMatchText(output);
    assert.equal(presets.process.layer_height, '0.2');
    assert.equal(presets.process.wall_loops, '3', 'the preset prints 3 walls: 1 outer and 2 inner');

    const layers = perObjectLayers(output.gcode);
    const a = layers.get('CubeA.stl'), b = layers.get('CubeB.stl');
    assert.ok(a && b, `objects in the G-code: ${[...layers.keys()].join(', ')}`);
    // As the CLI printed them: CubeA at 0.2, 0.3, 0.4 … (199 layers), CubeB at 0.2, 0.4 … (100).
    assert.deepEqual(a.zs, zSteps(0.2, 0.1, 20));
    assert.deepEqual(b.zs, zSteps(0.2, 0.2, 20));
    assert.equal(output.stats.layers, 199);

    // Z = 10: CubeA's 4 inner loops at half the height extrude what CubeB's 2 do (the CLI: 4.78
    // vs 4.76 mm of filament), along about twice the path; each has one outer loop.
    const feature = (layer: ObjectLayers, type: string) => layer.at10.get(type) ?? { e: 0, length: 0 };
    const [innerA, innerB] = [feature(a, 'Inner wall'), feature(b, 'Inner wall')];
    const [outerA, outerB] = [feature(a, 'Outer wall'), feature(b, 'Outer wall')];
    t.diagnostic(
      `Z 10 inner wall: CubeA ${innerA.e.toFixed(2)} mm over ${innerA.length.toFixed(0)} mm, CubeB ${innerB.e.toFixed(2)} mm over ${innerB.length.toFixed(0)} mm; ` +
        `outer wall ${outerA.length.toFixed(0)} / ${outerB.length.toFixed(0)} mm`,
    );
    assert.ok(Math.abs(innerA.e / innerB.e - 1) < 0.05, `inner wall filament ratio ${(innerA.e / innerB.e).toFixed(3)}`);
    assert.ok(innerA.length / innerB.length > 1.8 && innerA.length / innerB.length < 2.1, `inner wall path ratio ${(innerA.length / innerB.length).toFixed(3)}`);
    assert.ok(Math.abs(outerA.length / outerB.length - 1) < 0.02, `outer wall path ratio ${(outerA.length / outerB.length).toFixed(3)}`);

    // Every wall bead is as tall as its own object's layers (the preview draws Orca's heights).
    const { roles, extrusions } = output.toolpaths!;
    const heights = output.toolpathExtras!.height;
    const wallRoles = new Set(['Inner wall', 'Outer wall'].map((role) => roles.indexOf(role)));
    const seen = { a: new Set<number>(), b: new Set<number>() };
    for (let s = 0; s < extrusions.count; s++) {
      const z = extrusions.positions[s * 6 + 5];
      if (!wallRoles.has(extrusions.roleIndex[s]) || z < 0.25) continue; // the first layer is 0.2 for both
      const x = extrusions.positions[s * 6 + 3];
      if (x < 95) seen.a.add(Math.round(heights[s] * 1000));
      else seen.b.add(Math.round(heights[s] * 1000));
    }
    assert.deepEqual([...seen.a], [100], 'CubeA wall heights (µm)');
    assert.deepEqual([...seen.b], [200], 'CubeB wall heights (µm)');
  });

