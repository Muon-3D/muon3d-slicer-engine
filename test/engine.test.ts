    assert.ok(pattern.enumValues.every((value) => value in pattern.enumKeys!), 'every listed value is accepted');

    // Orca's JSON encoding: vectors as arrays of text, nullable per-filament overrides.
    assert.deepEqual(defs.options.printable_area.default, ['0x0', '200x0', '200x200', '0x200']);
